#!/usr/bin/env python3
"""Generate `src/expr/pytables.rs`: CPython's Unicode data for `str` semantics.

The expression built-ins mirror upstream `linkml-map`, whose string functions are
CPython's own (`str.upper`, `str.title`, `repr`, `int()`, `float()`...). Rust's
standard library follows a newer Unicode version than CPython 3.13 (Unicode 15.1),
so the case mappings and the printable/cased/decimal sets are taken from the
interpreter itself instead of from `std`. Everything is read through the public
`str` API (`upper`, `lower`, `isprintable`, `isdecimal`, ...) and `unicodedata`.

Regenerate with the interpreter whose behaviour should be matched, for instance
after upstream moves to a newer Python (3.14 ships Unicode 16.0):

    python3.14 crates/linkml-map-core/tools/gen_pytables.py \
        > crates/linkml-map-core/src/expr/pytables.rs
    cargo test -p linkml-map-core

The output names the interpreter and Unicode version in its header. Running the
script with `--check FILE` instead of redirecting exits 1 when FILE is stale.
"""

from __future__ import annotations

import sys
import unicodedata

SURROGATES = range(0xD800, 0xE000)
CPS = [c for c in range(0x110000) if c not in SURROGATES]


def ranges(cps: list[int]) -> list[tuple[int, int]]:
    """Merge a sorted code point list into inclusive ranges."""
    out: list[tuple[int, int]] = []
    for c in cps:
        if out and out[-1][1] == c - 1:
            out[-1] = (out[-1][0], c)
        else:
            out.append((c, c))
    return out


def hex_(n: int) -> str:
    return f"0x{n:X}"


def range_table(name: str, doc: str, rs: list[tuple[int, int]]) -> str:
    body = ", ".join(f"({hex_(a)}, {hex_(b)})" for a, b in rs)
    return f"{doc}\npub(crate) const {name}: &[(u32, u32)] = &[{body}];\n"


def rust_str(s: str) -> str:
    return '"' + "".join(f"\\u{{{ord(ch):x}}}" for ch in s) + '"'


def runs(mapping: dict[int, int]) -> list[tuple[int, int, int, int]]:
    """Group `cp -> mapped cp` into `(first, last, stride, delta)` runs.

    A run covers `first, first + stride, ...` up to `last`, each mapping to its
    own code point plus `delta` (so `A..Z -> a..z` is `(0x41, 0x5A, 1, 32)` and the
    alternating `Ā ā Ă ă ...` of Latin Extended-A is a stride-2 run).
    """
    out: list[tuple[int, int, int, int]] = []
    items = sorted(mapping.items())
    i = 0
    while i < len(items):
        cp, to = items[i]
        delta = to - cp
        stride = 1
        j = i
        if i + 1 < len(items) and items[i + 1][1] - items[i + 1][0] == delta:
            stride = items[i + 1][0] - cp
            j = i + 1
            while (
                j + 1 < len(items)
                and items[j + 1][0] - items[j][0] == stride
                and items[j + 1][1] - items[j + 1][0] == delta
            ):
                j += 1
        out.append((cp, items[j][0], stride, delta))
        i = j + 1
    return out


def case_tables(prefix: str, fn_name: str, fn) -> str:
    simple: dict[int, int] = {}
    special: list[tuple[int, str]] = []
    for c in CPS:
        ch = chr(c)
        m = fn(ch)
        if m == ch:
            continue
        if len(m) == 1:
            simple[c] = ord(m)
        else:
            special.append((c, m))
    rs = runs(simple)
    run_body = ", ".join(f"({hex_(a)}, {hex_(b)}, {s}, {d})" for a, b, s, d in rs)
    special_body = ", ".join(f"({hex_(c)}, {rust_str(m)})" for c, m in special)
    return (
        f"/// `str.{fn_name}()` of the characters with a single-character mapping, as\n"
        f"/// `(first, last, stride, delta)` runs: `first, first + stride, ...` up to `last` map\n"
        f"/// to themselves plus `delta`. Sorted by `first`; characters not covered map to themselves.\n"
        f"pub(crate) const {prefix}_RUNS: &[(u32, u32, u32, i32)] = &[{run_body}];\n\n"
        f"/// `str.{fn_name}()` of the characters whose mapping is longer than one character.\n"
        f"/// Sorted by code point.\n"
        f"pub(crate) const {prefix}_SPECIAL: &[(u32, &str)] = &[{special_body}];\n"
    )


def main() -> int:
    check = None
    if len(sys.argv) > 2 and sys.argv[1] == "--check":
        check = sys.argv[2]
    parts: list[str] = []
    parts.append(
        "//! Unicode data for CPython `str` semantics, generated by\n"
        "//! `tools/gen_pytables.py` from CPython "
        f"{sys.version.split()[0]} (Unicode {unicodedata.unidata_version}); do not edit by hand.\n"
        "//!\n"
        "//! Rust's standard library tracks a newer Unicode version than CPython, so the\n"
        "//! `str` methods that depend on character data read these tables instead of\n"
        "//! `char`'s. Regenerate them (see the script) when the Python version to match\n"
        "//! changes.\n"
    )
    parts.append(
        "/// Titlecase letters (general category `Lt`): neither `Uppercase` nor `Lowercase`, but `Cased`.\n"
        "pub(crate) const TITLECASE_LETTERS: &[u32] = &["
        + ", ".join(hex_(c) for c in CPS if unicodedata.category(chr(c)) == "Lt")
        + "];\n"
    )
    cased = [c for c in CPS if chr(c).islower() or chr(c).isupper() or unicodedata.category(chr(c)) == "Lt"]
    parts.append(
        range_table(
            "CASED",
            "/// The `Cased` property (`Lowercase` + `Uppercase` + `Lt`): `str.title`'s word\n"
            "/// boundaries and the final-sigma rule. Inclusive ranges, sorted.",
            ranges(cased),
        )
    )
    title_exc = [(c, chr(c).title()) for c in CPS if chr(c).title() != chr(c).upper()]
    parts.append(
        "/// Characters whose `str.title()` (full titlecase mapping) differs from `str.upper()`.\n"
        "/// Sorted by code point.\n"
        "pub(crate) const TITLE_EXCEPTIONS: &[(u32, &str)] = &["
        + ", ".join(f"({hex_(c)}, {rust_str(m)})" for c, m in title_exc)
        + "];\n"
    )
    parts.append(case_tables("UPPER", "upper", str.upper))
    parts.append(case_tables("LOWER", "lower", str.lower))
    parts.append(case_tables("CASEFOLD", "casefold", str.casefold))
    parts.append(
        range_table(
            "UPPERCASE",
            "/// `str.isupper()` of the character alone (the `Uppercase` property), which `swapcase` tests.",
            ranges([c for c in CPS if chr(c).isupper()]),
        )
    )
    parts.append(
        range_table(
            "LOWERCASE",
            "/// `str.islower()` of the character alone (the `Lowercase` property), which `swapcase` tests.",
            ranges([c for c in CPS if chr(c).islower()]),
        )
    )

    def case_ignorable(c: int) -> bool:
        ch = chr(c)
        # Final-sigma probes: `A<ch>Σ` is final unless <ch> is neither ignorable nor cased;
        # `1<ch>Σ` is final only when <ch> is cased and not skipped as ignorable.
        return ("A" + ch + "Σ").lower().endswith("ς") and ("1" + ch + "Σ").lower().endswith("σ")

    parts.append(
        range_table(
            "CASE_IGNORABLE",
            "/// `Case_Ignorable` ranges (inclusive), probed through CPython's final-sigma rule.",
            ranges([c for c in CPS if case_ignorable(c)]),
        )
    )
    parts.append(
        range_table(
            "DECIMAL_DIGITS",
            "/// General category `Nd` ranges (inclusive): what `\\d` and `str.isdecimal` accept.",
            ranges([c for c in CPS if chr(c).isdecimal()]),
        )
    )
    parts.append(
        range_table(
            "PY_SPACE",
            "/// Characters for which `str.isspace()` is true (the default `strip`/`split` set).",
            ranges([c for c in CPS if chr(c).isspace()]),
        )
    )
    parts.append(
        range_table(
            "NON_PRINTABLE",
            "/// Characters for which `str.isprintable()` is false (`Cc`, `Cf`, `Co`, `Cn`, `Zl`, `Zp`\n"
            "/// and `Zs` other than the ASCII space), which `repr()` escapes. Inclusive ranges, sorted.",
            ranges([c for c in CPS if not chr(c).isprintable()]),
        )
    )
    parts.append(
        range_table(
            "ALPHA",
            "/// `str.isalpha()` (categories Lm, Lt, Lu, Ll, Lo). Inclusive ranges, sorted.",
            ranges([c for c in CPS if chr(c).isalpha()]),
        )
    )
    parts.append(
        range_table(
            "DIGIT",
            "/// `str.isdigit()` (Numeric_Type Digit or Decimal). Inclusive ranges, sorted.",
            ranges([c for c in CPS if chr(c).isdigit()]),
        )
    )
    parts.append(
        range_table(
            "NUMERIC",
            "/// `str.isnumeric()`. Inclusive ranges, sorted.",
            ranges([c for c in CPS if chr(c).isnumeric()]),
        )
    )
    parts.append(
        range_table(
            "XID_START",
            "/// `str.isidentifier()` of the character alone (XID_Start, plus `_`).",
            ranges([c for c in CPS if chr(c).isidentifier()]),
        )
    )
    parts.append(
        range_table(
            "XID_CONTINUE",
            "/// `('a' + c).isidentifier()` (XID_Continue).",
            ranges([c for c in CPS if ("a" + chr(c)).isidentifier()]),
        )
    )
    out = "\n".join(parts)
    if check:
        return 0 if open(check, encoding="utf-8").read() == out else 1
    sys.stdout.write(out)
    return 0


if __name__ == "__main__":
    sys.exit(main())
